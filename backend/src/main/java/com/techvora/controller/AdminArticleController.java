package com.techvora.controller;

import com.techvora.dto.ArticleRequest;
import com.techvora.entity.Article;
import com.techvora.entity.User;
import com.techvora.service.ArticleService;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/v1/admin/articles")
@RequiredArgsConstructor
public class AdminArticleController {

    private final ArticleService articleService;

    @PostMapping
    @PreAuthorize("hasAnyRole('ADMIN', 'EDITOR', 'AUTHOR')")
    public ResponseEntity<com.techvora.dto.ArticleResponse> createArticle(
            @RequestBody ArticleRequest request,
            @AuthenticationPrincipal User author) {
        
        Article created = articleService.createArticle(request, author);
        return ResponseEntity.ok(articleService.mapToResponse(created));
    }

    @GetMapping
    @PreAuthorize("hasAnyRole('ADMIN', 'EDITOR', 'AUTHOR')")
    public ResponseEntity<List<Article>> getAllArticles() {
        return ResponseEntity.ok(articleService.getAllArticles());
    }

    @GetMapping("/{id}")
    @PreAuthorize("hasAnyRole('ADMIN', 'EDITOR', 'AUTHOR')")
    public ResponseEntity<com.techvora.dto.ArticleResponse> getArticleById(@PathVariable java.util.UUID id) {
        Article article = articleService.getArticleById(id);
        return ResponseEntity.ok(articleService.mapToResponse(article));
    }

    @PutMapping("/{id}")
    @PreAuthorize("hasAnyRole('ADMIN', 'EDITOR', 'AUTHOR')")
    public ResponseEntity<com.techvora.dto.ArticleResponse> updateArticle(
            @PathVariable java.util.UUID id,
            @RequestBody ArticleRequest request) {
        
        Article existingArticle = articleService.getArticleById(id);
        Article updated = articleService.updateArticle(existingArticle, request);
        return ResponseEntity.ok(articleService.mapToResponse(updated));
    }

    @DeleteMapping("/{id}")
    @PreAuthorize("hasAnyRole('ADMIN', 'EDITOR', 'AUTHOR')")
    public ResponseEntity<Void> deleteArticle(@PathVariable java.util.UUID id) {
        articleService.deleteArticle(id);
        return ResponseEntity.noContent().build();
    }
}












































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































